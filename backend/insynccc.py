def filter_documents_by_keyword(keyword, documents, max_results=5):
    k = keyword.lower()
    out = [{"chunk_id": i, "text": d, "character_count": len(d)}
           for i, d in enumerate(documents) if k in d.lower()]
    print(f"Found {len(out)} passages matching '{keyword}'.")
    return out[:max_results]

